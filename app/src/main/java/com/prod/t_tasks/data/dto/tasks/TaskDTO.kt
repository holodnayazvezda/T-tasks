package com.prod.t_tasks.data.dto.tasks

import com.prod.t_tasks.domain.model.trip.TripsTask
import kotlinx.serialization.Serializable

@Serializable
data class TaskDTO(
	val id: Long,
	val autogenerated: Boolean,
	val status: String,
	val is_common: Boolean,
	val categories: List<TaskCategoryDTO>
) {
	fun mapToDomain(): TripsTask = TripsTask(
		id = id,
		autogenerated = autogenerated,
		status = status,
		isCommon = is_common,
		categories = categories.map { it.mapToDomain() }
	)
}