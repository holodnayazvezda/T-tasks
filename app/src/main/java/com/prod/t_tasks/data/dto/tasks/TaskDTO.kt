package com.prod.t_tasks.data.dto.tasks

import com.prod.t_tasks.data.data_providers.local_db.entities.TaskEntity
import com.prod.t_tasks.data.dto.trips.isoToTimestamp
import com.prod.t_tasks.domain.model.trip.TripsTask
import kotlinx.serialization.Serializable

@Serializable
data class TaskDTO(
	val id: Long,
	val title: String,
	val description: String?,
	val autogenerated: Boolean,
	val status: String,
	val is_common: Boolean,
	val due_time: String,
	val categories: List<TaskCategoryDTO>
) {
	fun mapToDomain(): TripsTask = TripsTask(
		id = id,
		autogenerated = autogenerated,
		status = status,
		isCommon = is_common,
		categories = categories.map { it.mapToDomain() },
		whatToDo = description?.substringBefore('.'),
		reason = description?.substringAfter('.'),
		title = title,
		common = is_common,
		deadline = isoToTimestamp(due_time)
	)

	fun mapToDB(): TaskEntity = TaskEntity(
		id = id,
		name = title,
		whatToDo = description?.substringBefore('.') ?: "",
		reason = description?.substringAfter('.') ?: "",
		typeIds = categories.map { it.id }.joinToString("|"),
		deadline = isoToTimestamp(due_time),
		archived = status == "completed",
		common = is_common
	)
}

