package com.prod.t_tasks.domain.model.trip

import java.time.Instant

enum class DestinationType {
	DOMESTIC,
	INTERNATIONAL
}

enum class TravelType {
	PLANE,
	CAR,
	TRAIN
}

enum class TaskStatus {
	PENDING,
	IN_PROGRESS,
	CANCELED,
	COMPLETED
}

data class TaskCategory(
	val id: Long,
	val name: String
)

data class Task(
	val id: Long,
	val autogenerated: Boolean,
	val status: TaskStatus,
	val categories: List<TaskCategory>
)

data class TripMember(
	val firstName: String,
	val secondName: String,
	val email: String,
	val avatarFileKey: String?
)

data class Trip(
	val id: Long,
	val ownerId: Long,
	val startDate: Instant,
	val endDate: Instant,
	val destinationType: DestinationType?,
	val city: String?,
	val country: String?,
	val description: String?,
	val purpose: String?,
	val transport: TravelType,
	val withKids: Boolean,
	val withPets: Boolean,
	val kidsAges: List<Int>,
	val members: List<TripMember>,
	val tasks: List<Task>
)

data class TripCreateData(
	val startDate: String,
	val endDate: String,
	val destinationType: DestinationType?,
	val city: String?,
	val country: String?,
	val description: String?,
	val purpose: String?,
	val transport: TravelType,
	val withKids: Boolean,
	val withPets: Boolean,
	val kidsAges: List<Int>,
	val autoGenerateTasks: Boolean
)

data class TaskCreateData(
	val title: String,
	val description: String?,
	val dueDate: String?,
	val dueTime: String?,
	val categories: List<TaskCategory>,
	val autogenerated: Boolean
)
